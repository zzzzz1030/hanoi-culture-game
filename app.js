let rotation=0,spinning=false;

function buildWheel(){
  const wheel=document.getElementById("prizeWheel");
  const n=wheelItems.length;
  const slice=360/n;
  const gradient=[];
  wheelItems.forEach((it,i)=>gradient.push(`${it.color} ${i*slice}deg ${(i+1)*slice}deg`));
  wheel.style.background=`conic-gradient(${gradient.join(",")})`;

  wheel.innerHTML=wheelItems.map((it,i)=>{
    const angle=i*slice+slice/2;
    return `<div class="wheel-label" style="transform:rotate(${angle}deg);--counter-rotate:-${angle}deg"><span>${it.label.replace("\n","<br>")}</span></div>`
  }).join("");

  document.getElementById("wheelLegend").innerHTML=wheelItems.map(it=>{
    return `<div class="legend-item"><span class="legend-dot" style="background:${it.color}"></span><div><b>${it.label.replace("\n"," ")}</b><small>${it.desc}</small></div></div>`
  }).join("");
}

function clampScore(x){return Math.max(0,x)}

function pickRandomOtherTeam(excluded){
  const list=[1,2,3,4].filter(t=>t!==excluded);
  return list[Math.floor(Math.random()*list.length)];
}

function applyWheelItem(item){
  let text="";
  if(item.type==="add"){
    scores[item.team]=clampScore(scores[item.team]+item.points);
    text=`🎉 Tổ ${item.team} được cộng ${item.points} điểm!`;
  }else if(item.type==="subtract"){
    scores[item.team]=clampScore(scores[item.team]+item.points);
    text=`⚠️ Tổ ${item.team} bị trừ ${Math.abs(item.points)} điểm!`;
  }else if(item.type==="addRandomTarget"){
    const t=Math.floor(Math.random()*4)+1;
    scores[t]=clampScore(scores[t]+10);
    text=`🎉 Tổ ${t} ngẫu nhiên được +10 điểm!`;
  }else if(item.type==="subtractRandomTarget"){
    const t=Math.floor(Math.random()*4)+1;
    scores[t]=clampScore(scores[t]-10);
    text=`⚠️ Tổ ${t} ngẫu nhiên bị −10 điểm!`;
  }else if(item.type==="takeOther"){
    const winner=Math.floor(Math.random()*4)+1;
    const other=pickRandomOtherTeam(winner);
    const actual=Math.min(5,scores[other]);
    scores[other]-=actual;
    scores[winner]+=actual;
    text=actual>0
      ? `🔄 Tổ ${winner} lấy ${actual} điểm từ Tổ ${other}!`
      : `🔄 Tổ ${winner} được quyền lấy điểm, nhưng Tổ ${other} không có điểm để chuyển.`;
  }else if(item.type==="exchange"){
    const a=Math.floor(Math.random()*4)+1;
    const b=pickRandomOtherTeam(a);
    const amount=Math.min(5,scores[a]);
    scores[a]-=amount;scores[b]+=amount;
    text=amount>0
      ? `🔄 Trao đổi: chuyển ${amount} điểm từ Tổ ${a} sang Tổ ${b}!`
      : `🔄 Tổ ${a} không có đủ điểm để trao đổi.`;
  }
  save();updateScore();document.getElementById("wheelResult").textContent=text;
}

function spinWheel(){
  if(spinning)return;
  spinning=true;
  document.getElementById("spinButton").disabled=true;

  const index=Math.floor(Math.random()*wheelItems.length);
  const slice=360/wheelItems.length;

  // Mũi tên ở 12 giờ (0 độ). Đưa tâm ô thắng vào vị trí 12 giờ.
  const targetCenter=index*slice+slice/2;
  const normalized=(360-targetCenter+360)%360;

  rotation += 360*6 + normalized;
  document.getElementById("prizeWheel").style.transform=`rotate(${rotation}deg)`;

  setTimeout(()=>{
    applyWheelItem(wheelItems[index]);
    spinning=false;
    document.getElementById("spinButton").disabled=false;
  },5600);
}

function updateScore(){
  const max=Math.max(0,...Object.values(scores));
  document.getElementById("scoreBoard").innerHTML=[1,2,3,4].map(t=>{
    const leading=Number(scores[t])===max&&max>0;
    return `<div class="score-card ${leading?'leading':''}"><h2>${leading?'🏆 ':''}Tổ ${t}</h2><div class="score-value">${scores[t]} điểm</div></div>`;
  }).join("");
}
